def template_options(template, options):
    return {c: template.format(o=text.rstrip('.')) for c, text in options.items()}


def authored(row, templates, explicit, number):
    if number in explicit:
        return dict(zip('ABCD', explicit[number]))
    return template_options(templates[number], row['options'])


def card(row):
    # All 48 cards have identical count-query grammar; keep the full time clause.
    temporal, count = row['question'].rsplit(', how many ', 1)
    temporal = temporal.replace('At the moment when ', 'When ')
    match = re.fullmatch(r'(\w+) cards (does|has) (Player \d) (hold|played so far|drawn so far)\?', count)
    assert match, row['id']
    color, auxiliary, player, action = match.groups()
