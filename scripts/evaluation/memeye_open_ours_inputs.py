"""Answer-free Open adaptation of the frozen 195/185/199 MemEye methods.

The MCQ experiment used option-derived hypotheses. Open questions instead use
four fresh Qwen hypotheses, generated by the existing MemGallery candidate
pipeline from the question and its cached question-image caption only.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / '.vendor'), str(ROOT)]
for key, value in {'HF_HUB_OFFLINE': '1', 'TOKENIZERS_PARALLELISM': 'false',
                   'OMP_NUM_THREADS': '4', 'OPENBLAS_NUM_THREADS': '4'}.items():
    os.environ.setdefault(key, value)

import numpy as np
from scripts.evaluation import mem_gallery_master_reader as common
from scripts.evaluation.memeye_open_semrag_inputs import SYSTEM, payload_hash
from scripts.memory.caption_visual_master import (
    load_text_encoder, load_clip_text_encoder, encode_text, normalize,
)
from scripts.memory.online_zscore import ZScoreWeighting

BASELINE = ROOT / 'results/memeye_qwen_semrag_open_20261105'
MCQ = ROOT / 'results/memeye_qwen_zscore_joint_search_20261024'
STORES = ROOT / 'results/memory_stores_20261023'
FROZEN = ROOT / 'reports/adaptive_retrieval_comparison_20261020/inputs_by_domain'
DEFAULT = ROOT / 'results/memeye_qwen_other_open_20261105/ours'
SPECS = {
    'ours_1': {'original_condition': 'master_answer_query', 'mcq_correct': 195,
               'code_method': 'caption_visual_master', 'ridge': None, 'alpha': 0.},
    'ours_2': {'original_condition': 'baseline_question_only__l0p03_a1', 'mcq_correct': 185,
               'code_method': 'natural+zscore', 'ridge': .03, 'alpha': 1.},
    'ours_1_ours_2': {'original_condition': 'master_answer_query__l0p03_a1', 'mcq_correct': 199,
               'code_method': 'caption_visual_master+zscore', 'ridge': .03, 'alpha': 1.},
}
sha, dump, digest, rows = common.sha, common.dump, common.digest, common.read_lines


def read(path):
    return json.loads(Path(path).read_text())


def write_rows(path, values):
    path = Path(path)
    text = ''.join(json.dumps(v, ensure_ascii=False, allow_nan=False) + '\n' for v in values)
    if path.exists() and path.read_text() != text:
        raise ValueError(f'Frozen output differs: {path}')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def verify(hashes):
    for path, expected in hashes.items():
        if sha(path) != expected:
            raise ValueError('Frozen input changed: ' + str(path))


def prepare(root):
    root.mkdir(parents=True, exist_ok=True)
    existing = root / 'preparation_protocol.json'
    if existing.exists():
        p = read(existing)
        verify(p['source_sha256']); verify(p['artifact_sha256'])
        return p
    questions = rows(BASELINE / 'inputs/questions.jsonl')
    assert len(questions) == len(common.by_id(questions)) == 371
    assert all(not set(q) & {'answer', 'options', 'gold_ids', 'gold_choice', 'clue'} for q in questions)
    # MCQ responses are inspected only to identify the screenshot's exact runs.
    summary, responses = read(MCQ / 'summary.json'), rows(MCQ / 'reader/responses.jsonl')
    source_counts = {}
    for method, spec in SPECS.items():
        original = [r for r in responses if r['condition'] == spec['original_condition']]
        assert len(original) == 371
        assert sum(bool(r['correct']) for r in original) == spec['mcq_correct']
        assert summary['overall'][spec['original_condition']]['correct'] == spec['mcq_correct']
        source_counts[method] = {'correct': spec['mcq_correct'], 'questions': 371,
                                 'condition': spec['original_condition']}
    sources = [Path(__file__), BASELINE / 'protocol.json', BASELINE / 'inputs/questions.jsonl',
               BASELINE / 'inputs/gold.jsonl', BASELINE / 'reader_manifest.jsonl',
               BASELINE / 'retrieval.jsonl', MCQ / 'protocol.json', MCQ / 'summary.json',
               MCQ / 'reader/protocol.json', MCQ / 'reader/responses.jsonl',
               Path(common.__file__), ROOT / 'scripts/evaluation/memeye_open_semrag_inputs.py',
               ROOT / 'scripts/memory/caption_visual_master.py',
               ROOT / 'scripts/memory/online_zscore.py', ROOT / 'scripts/memory/ridge_whitening.py']
    source_hashes = {str(p): sha(p) for p in sources}
    for name in ('questions.jsonl', 'gold.jsonl'):
        (root / 'inputs').mkdir(exist_ok=True)
        shutil.copyfile(BASELINE / 'inputs' / name, root / 'inputs' / name)
    candidate_inputs = [{'id': q['id'], 'question': q['question'],
                         'query_image_caption': '\n'.join(q['query_image_captions'])} for q in questions]
    candidate_path = root / 'inputs/sanitized_candidate_inputs.jsonl'
    write_rows(candidate_path, candidate_inputs)
    p = {'dataset': 'MemEye Open', 'questions': 371, 'source_mcq': source_counts,
         'methods': SPECS, 'memory_leaves': 438, 'masters': 88, 'top_k': 5,
         'open_adaptation': 'Four fresh Qwen retrieval hypotheses generated with the existing MemGallery prompt and parser from Open question plus cached query-image caption. No provided MCQ options, gold, history or retrieved evidence in candidate input.',
         'candidate_shared_between': ['ours_1', 'ours_1_ours_2'],
         'query_policy': 'Official Open question plus identical cached Qwen query-image caption.',
         'reader_policy': 'Same baseline Open system and formatting; top5 original dialogue+full caption, Open question and original query images. Retrieval hypotheses are not reader evidence.',
         'source_sha256': source_hashes,
         'artifact_sha256': {str(p): sha(p) for p in (candidate_path,
             root / 'inputs/questions.jsonl', root / 'inputs/gold.jsonl')}}
    dump(existing, p)
    print(json.dumps({'stage': 'prepare', 'questions': 371, 'source_mcq': source_counts}), flush=True)
    return p


def retrieve(root, device):
    import torch
    torch.set_num_threads(4)
    preparation = prepare(root)
    candidate_validation = read(root / 'candidate_validation.json')
    assert candidate_validation['passed'] and candidate_validation['questions'] == 371
    assert sha(root / 'candidates.jsonl') == candidate_validation['candidates_sha256']
    questions = rows(root / 'inputs/questions.jsonl')
    candidates = common.by_id(rows(root / 'candidates.jsonl'))
    assert set(candidates) == {q['id'] for q in questions}
    sanitized = common.by_id(rows(root / 'inputs/sanitized_candidate_inputs.jsonl'))
    for qid, candidate in candidates.items():
        assert candidate['source_input_sha256'] == digest(sanitized[qid])
        assert candidate['gold_or_history_used'] is False
    sources = dict(preparation['source_sha256'])
    sources.update({str(p): sha(p) for p in [root / 'preparation_protocol.json',
        root / 'candidates.jsonl', root / 'candidate_generation_protocol.json', root / 'candidate_validation.json']})
    old_protocol = read(MCQ / 'protocol.json')
    baseline_protocol = read(BASELINE / 'protocol.json')
    baseline_rankings = common.by_id(rows(BASELINE / 'retrieval.jsonl'))
    expected_texts = {r['id']: r['reader_text'] for r in rows(ROOT / 'data/independent_visual_inputs/retrieval_memories.jsonl')}
    sources[str(ROOT / 'data/independent_visual_inputs/retrieval_memories.jsonl')] = sha(ROOT / 'data/independent_visual_inputs/retrieval_memories.jsonl')
    metadata = read(STORES / questions[0]['task'] / 'caption_visual_master/memory.json')['encoding']
    encoder = load_text_encoder(metadata['text_encoder'], device)
    clip, tokenizer, clip_limit = load_clip_text_encoder(metadata['image_encoder'], device)
    results = {m: [] for m in SPECS}
    manifests = {m: [] for m in SPECS}
    total_leaves = total_masters = baseline_checks = 0
    max_baseline_error = max_query_tokens = 0
    group_audits = []
    for task in dict.fromkeys(q['task'] for q in questions):
        state = STORES / task / 'caption_visual_master'
        manifest = read(state / 'memory.json')
        assert manifest['encoding']['text_encoder'] == metadata['text_encoder']
        assert manifest['encoding']['query_prefix'] == metadata['query_prefix']
        for key, record in manifest['files'].items():
            path = state / record['path']
            assert sha(path) == record['sha256'] == old_protocol['source_sha256'][str(path)]
            sources[str(path)] = sha(path)
        assert sha(state / 'memory.json') == old_protocol['source_sha256'][str(state / 'memory.json')]
        sources[str(state / 'memory.json')] = sha(state / 'memory.json')
        graph, leaves = read(state / 'graph.json'), read(state / 'leaves.json')
        nodes, masters = graph['image_nodes'], graph['masters']
        ids = [leaf['memory_id'] for leaf in leaves]
        assert [n['id'] for n in nodes] == [l['image_id'] for l in leaves]
        texts = [l['dialogue'] + '\nMemory description: ' + l['caption'] for l in leaves]
        assert all(t == expected_texts[mid] for mid, t in zip(ids, texts))
        sums = np.load(state / 'master_sums.npy', allow_pickle=False)
        centers = normalize([sums[m['visual_mean_ref']['row']] * m['visual_mean_ref']['scale'] for m in masters])
        groups = [np.array([i for i, n in enumerate(nodes) if n['master_id'] == m['id']], dtype=int) for m in masters]
        assert sorted(int(i) for group in groups for i in group) == list(range(len(ids)))
        for m, group in zip(masters, groups):
            assert len(group) == m['n'] and set(m['member_ids']) == {nodes[i]['id'] for i in group}
        source_input = FROZEN / task / 'inputs.json'
        features_path = FROZEN / task / 'features.npz'
        for path in (source_input, features_path):
            assert sha(path) == baseline_protocol['source_sha256'][str(path)]
            sources[str(path)] = sha(path)
        original = read(source_input)
        with np.load(features_path) as features:
            vectors = features['bge_leaf'].copy()
            old_queries = {q['id']: (q['retrieval_query'], features['bge_query'][i].copy())
                           for i, q in enumerate(original['questions'])}
        assert vectors.shape == (len(ids), 384) and vectors.dtype == np.float64
        assert [l['memory_id'] for l in original['leaves']] == ids
        selected = [q for q in questions if q['task'] == task]
        changed = [q for q in selected if old_queries[q['id']][0] != q['retrieval_query']]
        fresh = encode_text(encoder, [q['retrieval_query'] for q in changed], metadata['query_prefix']) if changed else []
        new_base = {q['id']: v for q, v in zip(changed, fresh)}
        expanded = [q['retrieval_query'] + '\nCandidate answer: ' + h
                    for q in selected for h in candidates[q['id']]['candidate_statements']]
        max_query_tokens = max(max_query_tokens, max(len(x) for x in encoder.tokenizer(
            [metadata['query_prefix'] + t for t in expanded], truncation=False)['input_ids']))
        expanded_vectors = encode_text(encoder, expanded, metadata['query_prefix']).reshape(len(selected), 4, -1)
        hypotheses = [h for q in selected for h in candidates[q['id']]['candidate_statements']]
        clip_vectors = []
        for start in range(0, len(hypotheses), 64):
            tokens = tokenizer(hypotheses[start:start + 64], padding=True, truncation=False, return_tensors='pt')
            assert tokens['input_ids'].shape[1] <= clip_limit
            tokens = tokens.to(next(clip.parameters()).device)
            with torch.inference_mode():
                clip_vectors.extend(clip(**tokens, return_dict=True).text_embeds.double().cpu().numpy())
        clip_vectors = normalize(clip_vectors).reshape(len(selected), 4, -1)
        for qi, q in enumerate(selected):
            qid = q['id']
            base_query = new_base.get(qid, old_queries[qid][1])
            baseline_scores = vectors @ base_query
            baseline_order = np.argsort(-baseline_scores, kind='stable')
            expected = baseline_rankings[qid]
            assert [ids[i] for i in baseline_order[:5]] == expected['top_memory_ids']
            expected_scores = dict(zip(expected['full_rank_memory_ids'], expected['full_rank_scores']))
            error = max(abs(float(s) - expected_scores[mid]) for mid, s in zip(ids, baseline_scores))
            assert error < 2e-6, (qid, error)
            max_baseline_error = max(max_baseline_error, error)
            baseline_checks += 1
            scores = {'ours_2': ZScoreWeighting(.03, 1.).apply(base_query, vectors)['weighted'],
                      'ours_1': np.empty(len(ids)), 'ours_1_ours_2': np.empty(len(ids))}
            similarities = centers @ clip_vectors[qi].T
            choices = np.argmax(similarities, axis=1)
            audits = []
            for mi, (master, group) in enumerate(zip(masters, groups)):
                selected_query = expanded_vectors[qi, choices[mi]]
                adjusted = ZScoreWeighting(.03, 1.).apply(selected_query, vectors[group])
                scores['ours_1'][group] = adjusted['raw']
                scores['ours_1_ours_2'][group] = adjusted['weighted']
                audits.append({'master_id': master['id'], 'memory_ids': [ids[i] for i in group],
                    'candidate_index': int(choices[mi]), 'selected_statement': candidates[qid]['candidate_statements'][choices[mi]],
                    'clip_statement_scores': similarities[mi].tolist(), 'raw': adjusted['raw'].tolist(),
                    'weighted': adjusted['weighted'].tolist(), 'raw_std': adjusted['raw_std'],
                    'raw_status': adjusted['raw_status'], 'z_status': adjusted['z_status']})
            group_audits.append({'id': qid, 'task': task, 'groups': audits})
            for method, values in scores.items():
                order = np.argsort(-values, kind='stable')
                top = order[:5]
                top_ids = [ids[i] for i in top]
                context = 'Retrieved dialogue and image descriptions (ranked by relevance):\n\n' + '\n\n'.join(
                    f'Memory {rank}: {texts[i]}' for rank, i in enumerate(top, 1))
                user_text = context + '\n\nQuestion:\n' + q['question'] + '\n\nAnswer concisely.'
                results[method].append({'id': qid, 'task': task, 'retrieval_query': q['retrieval_query'],
                    'top_memory_ids': top_ids, 'top_scores': [float(values[i]) for i in top],
                    'full_rank_memory_ids': [ids[i] for i in order],
                    'full_rank_scores': [float(values[i]) for i in order]})
                manifests[method].append({'id': qid, 'task': task, 'point': q['point'], 'question': q['question'],
                    'top_memory_ids': top_ids, 'context': context, 'query_image_paths': q['query_image_paths'],
                    'system': SYSTEM, 'user_text': user_text,
                    'payload_sha256': payload_hash(SYSTEM, user_text, q['query_image_paths'])})
        total_leaves += len(leaves); total_masters += len(masters)
        print(json.dumps({'stage': 'retrieval', 'task': task, 'questions': len(selected),
                          'leaves': len(leaves), 'masters': len(masters)}), flush=True)
    assert total_leaves == 438 and total_masters == 88 and baseline_checks == 371
    verify(sources)
    write_rows(root / 'master_query_audit.jsonl', group_audits)
    audit = {'passed': True, 'questions_per_method': 371, 'memory_leaves': total_leaves,
             'masters': total_masters, 'all_baseline_open_top5_reproduced': baseline_checks,
             'max_baseline_score_error': max_baseline_error, 'expanded_query_max_bge_tokens': max_query_tokens,
             'query_truncations': 0, 'candidates_shared': True, 'gold_or_mcq_options_used': False,
             'memory_rebuilt': False, 'all_contexts_five_distinct_memories': True}
    dump(root / 'retrieval_validation.json', audit)
    for method, spec in SPECS.items():
        out = root / method
        (out / 'inputs').mkdir(parents=True, exist_ok=True)
        for name in ('questions.jsonl', 'gold.jsonl'):
            shutil.copyfile(root / 'inputs' / name, out / 'inputs' / name)
        write_rows(out / 'retrieval.jsonl', results[method])
        write_rows(out / 'reader_manifest.jsonl', manifests[method])
        p = {'dataset': 'MemEye', 'evaluation_type': 'open_ended', 'stage': 'memeye_open_ours_inputs',
             'method': method, **spec, 'questions': 371, 'original_source_root': str(MCQ),
             'original_mcq_correct': spec['mcq_correct'], 'original_mcq_questions': 371,
             'memory_leaves': 438, 'masters': 88, 'top_k': 5, 'retrieval_device': device,
             'memory_text': 'Original historical dialogue plus full Qwen caption.',
             'query_policy': preparation['query_policy'], 'reader_policy': preparation['reader_policy'],
             'open_adaptation': preparation['open_adaptation'] if method != 'ours_2' else 'Use true Open question without candidates, options or gold.',
             'source_sha256': sources,
             'artifact_sha256': {str(path.relative_to(out)): sha(path) for path in (
                 out / 'inputs/questions.jsonl', out / 'inputs/gold.jsonl', out / 'retrieval.jsonl', out / 'reader_manifest.jsonl')}}
        dump(out / 'protocol.json', p)
    print(json.dumps(audit), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--phase', choices=('prepare', 'candidates', 'retrieve'), required=True)
    parser.add_argument('--root', type=Path, default=DEFAULT)
    parser.add_argument('--device', default='cpu')
    parser.add_argument('--batch-size', type=int, default=16)
    args = parser.parse_args(); args.root = args.root.resolve()
    if args.phase == 'prepare':
        prepare(args.root)
    elif args.phase == 'candidates':
        prepare(args.root)
        common.generate_candidates(args.root, args.device, args.batch_size, 3)
    else:
        retrieve(args.root, args.device)


if __name__ == '__main__':
    main()
