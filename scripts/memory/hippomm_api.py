"""MemEye HippoMM with provider-specific captions and all LLM roles replaced.

Retained images/CLIP features are model-independent and reused exactly. Event
summaries, fast decisions, visual rewrites, caption selection and answers are
generated by the selected provider. Detailed answers see selected originals.
"""
from concurrent.futures import ThreadPoolExecutor, as_completed
import json
from pathlib import Path
import threading
import time

import numpy as np

from scripts.memory import hippomm as base, hippomm_core as core, hippomm_inputs as inputs
from scripts.memory import hippomm_original as original, hippomm_api_transport as transport

ROOT = inputs.ROOT
TEMPLATE = ROOT / 'results/hippomm_original_controlled_20261104/memeye/offline'
CAPTIONS = {
    'gpt5': ROOT / 'results/memeye_gpt5_seed42_text_methods_20261025/caption_source',
    'deepseek': ROOT / 'results/memeye_deepseek_flash_seed42_full_20261025'}
METHOD = 'hippomm_original_full_api_backbone'


def manifest(directory, backbone):
    files = [Path(__file__), Path(transport.__file__), Path(original.__file__),
             Path(transport.gpt.__file__), Path(transport.deep.__file__),
             ROOT / 'scripts/evaluation/openai_backbone_transport.py',
             ROOT / 'scripts/evaluation/openai_chat_transport.py',
             ROOT / 'scripts/evaluation/openai_gpt54_seeded_transport.py']
    base.contract_at(Path(directory).parent / 'experiment_manifest.json', {
        'method': METHOD, 'backbone': backbone, 'model': transport.MODELS[backbone],
        'implementation': base.implementation_hashes() | {str(p): inputs.sha(p) for p in files}})


def caption_source(backbone):
    directory = CAPTIONS[backbone]
    record = json.loads((directory / 'completion_manifest.json').read_text())
    path = directory / 'captions.jsonl'
    if inputs.sha(path) != record['artifacts_sha256'][str(path)]:
        raise ValueError('Existing provider caption artifact differs from its completion record')
    captions = inputs.unique(inputs.read_lines(path))
    if len(captions) != 437:
        raise ValueError('Incomplete provider caption source')
    for row in captions.values():
        if row['model'] != transport.MODELS[backbone] or row['seed'] != 42 or not row['caption'].strip():
            raise ValueError('Caption model/seed/text mismatch')
    if backbone == 'deepseek':
        responses = inputs.unique(inputs.read_lines(directory / 'caption_generation/fresh_responses.jsonl'),
                                  'record_id')
    else:
        responses = {key: json.loads((directory / 'responses' / (key + '.json')).read_text())
                     for key in captions}
    for key, cap in captions.items():
        raw = responses[key]
        if (raw['returned_model'] != transport.MODELS[backbone] or raw['seed'] != 42
                or raw['finish_reason'] != 'stop' or raw.get('refusal')
                or raw['raw_response'].strip() != cap['caption'].strip()
                or raw['response_id'] != cap['response_id']):
            raise ValueError('Caption does not match successful original provider response')
    return directory, captions


def build(args):
    _, emap, image_map, _ = original.verify_memory(TEMPLATE)
    source, captions = caption_source(args.hippomm_backbone)
    args.output.mkdir(parents=True, exist_ok=True)
    manifest(args.output, args.hippomm_backbone)
    base.contract_at(args.output / 'build_contract.json', {
        'method': METHOD, 'backbone': args.hippomm_backbone, 'caption_source': str(source),
        'visual_template': str(TEMPLATE), 'max_output_tokens': args.hippomm_max_new_tokens,
        'representatives_and_vectors': 'identical to completed Qwen visual-only novelty filter',
        'summaries': 'fresh provider-specific summaries; no Qwen summary reuse'})
    if (args.output / 'memory.json').exists():
        load_memory(args.output, args.hippomm_backbone)
        print('Existing complete API-backbone memory verified.', flush=True)
        return
    events, provenance = [], []
    for old in emap.values():
        record = image_map[old['event_id']]
        src = TEMPLATE / record['file']
        cap = captions[inputs.sha(src)]
        events.append({**old, 'caption': cap['caption'], 'summary': ''})
        provenance.append({'event_id': old['event_id'], 'image_ref': old['representative_image'],
                           'caption_model': cap['model'], 'seed': 42, 'response_id': cap['response_id']})
        if args.hippomm_stage != 'prepare':
            original.copy_exact(src, args.output / record['file'])
    if args.hippomm_stage == 'prepare':
        base.dump(args.output / 'readiness.json', {'events': len(events), 'caption_coverage': len(provenance),
                  'model': transport.MODELS[args.hippomm_backbone]})
        return
    for name in ('dialogues.jsonl', 'image_mapping.jsonl', 'visual_embeddings.npz', 'representative_images.jsonl'):
        original.copy_exact(TEMPLATE / name, args.output / name)
    dialogues = inputs.unique(inputs.read_lines(args.output / 'dialogues.jsonl'))
    base.write_lines(args.output / 'caption_provenance.jsonl', provenance)
    errors = []

    def summarize(event):
        chat = transport.APIChat(args.output / 'llm_cache' / event['event_id'], args.hippomm_backbone,
                                 args.hippomm_api_env_file, args.hippomm_max_new_tokens)
        event = {**event, 'summary': chat('summary', core.summary_prompt(event, dialogues)).strip()}
        return event

    with ThreadPoolExecutor(max_workers=args.hippomm_api_workers) as pool:
        pending = {pool.submit(summarize, e): e['event_id'] for e in events}
        completed = {}
        for future in as_completed(pending):
            eid = pending[future]
            try:
                completed[eid] = future.result()
                print(json.dumps({'stage': 'summary', 'event_id': eid, 'done': len(completed),
                                  'total': len(events)}), flush=True)
            except Exception as exc:
                errors.append({'event_id': eid, 'type': type(exc).__name__, 'error': str(exc)})
                base.append(args.output / 'summary_errors.jsonl', errors[-1])
                if getattr(exc, 'kind', '') in ('auth', 'quota', 'model_mismatch', 'protocol'):
                    for f in pending:
                        f.cancel()
                    raise
    if errors:
        raise ValueError(f'{len(errors)} event summaries failed; successes cached for resume')
    events = [completed[e['event_id']] for e in events]
    base.write_lines(args.output / 'events.jsonl', events)
    memory_files = (*original.MEMORY_FILES, 'representative_images.jsonl', 'caption_provenance.jsonl')
    base.dump(args.output / 'memory.json', {'method': METHOD, 'backbone': args.hippomm_backbone,
        'model': transport.MODELS[args.hippomm_backbone], 'events': len(events),
        'dialogue_rounds': len(dialogues), 'caption_source': str(source),
        'original_image_bytes': sum(r['bytes'] for r in image_map.values()),
        'memory_artifact_bytes': sum((args.output / n).stat().st_size for n in memory_files),
        'max_output_tokens': args.hippomm_max_new_tokens})
    load_memory(args.output, args.hippomm_backbone)


def load_memory(directory, backbone):
    directory = Path(directory)
    manifest(directory, backbone)
    memory = json.loads((directory / 'memory.json').read_text())
    if memory['method'] != METHOD or memory['backbone'] != backbone:
        raise ValueError('Wrong API-backbone memory')
    events = inputs.read_lines(directory / 'events.jsonl')
    emap = inputs.unique(events, 'event_id')
    dialogues = inputs.unique(inputs.read_lines(directory / 'dialogues.jsonl'))
    images = inputs.unique(inputs.read_lines(directory / 'representative_images.jsonl'), 'event_id')
    captions = inputs.unique(inputs.read_lines(directory / 'caption_provenance.jsonl'), 'event_id')
    if set(emap) != set(images) or set(emap) != set(captions) or len(events) != memory['events']:
        raise ValueError('Memory/image/caption coverage differs')
    for e in events:
        if not e['summary'].strip() or not e['caption'].strip():
            raise ValueError('Missing memory text')
        if captions[e['event_id']]['caption_model'] != transport.MODELS[backbone]:
            raise ValueError('Mixed caption backbone')
        path = (directory / images[e['event_id']]['file']).resolve()
        if not path.is_relative_to((directory / 'images').resolve()) or not path.is_file():
            raise ValueError('Missing retained original image')
        if any(dialogues[mid]['task'] != e['task'] for mid in e['source_round_ids']):
            raise ValueError('Mixed task evidence')
    with np.load(directory / 'visual_embeddings.npz', allow_pickle=False) as data:
        if data['event_ids'].tolist() != [e['event_id'] for e in events]:
            raise ValueError('Visual vector/event alignment differs')
        vectors = dict(zip(data['event_ids'].tolist(), data['vectors']))
    return memory, events, vectors, dialogues, images


def prepare(args):
    memory, events, _, _, _ = load_memory(args.memory_dir, args.hippomm_backbone)
    if memory['max_output_tokens'] != args.hippomm_max_new_tokens:
        raise ValueError('Generation budget differs from memory construction')
    questions, _ = inputs.questions_input(args)
    args.output.mkdir(parents=True, exist_ok=True)
    manifest(args.output, args.hippomm_backbone)
    base.contract_at(args.output / 'protocol.json', {
        'method': METHOD, 'backbone': args.hippomm_backbone, 'model': memory['model'],
        'memory_dir': str(args.memory_dir.resolve()), 'questions': len(questions),
        'max_output_tokens': args.hippomm_max_new_tokens, 'top_k': 5,
        'confidence_threshold': .75, 'fallback_threshold': .4, 'fallback_score': .6,
        'evaluation_source': str(args.benchmark_manifest.resolve()),
        'seed': 42, 'query_recovery': 'original 3 attempts then at most 3 three-word-array attempts',
        'all_llm_roles': args.hippomm_backbone, 'original_images': 'selected representatives only in detailed final answers',
        'query_images': 'original question pixels in fast/final answers; no query captions used',
        'caption_source': memory['caption_source']})
    path = args.output / 'questions.jsonl'
    if path.exists() and inputs.read_lines(path) != questions:
        raise ValueError('Prepared questions changed')
    base.write_lines(path, questions)


def repaired_rewrite(chat, raw, prompt, calls, recovery):
    """The original three attempts already ran; now request three separate words."""
    try:
        core.parse_query(raw)
        return raw
    except (TypeError, ValueError):
        pass
    fix = ('Generate a visual search cue from the original question below. Return exactly THREE '
           'separate English words as JSON {"words":["word1","word2","word3"]}. '
           'Each element must contain one word with no whitespace. Use only objects or attributes '
           'explicitly mentioned; do not guess the answer.\nOriginal request:\n' + prompt)
    for attempt in range(3):
        result = chat('rewrite_format_recovery', fix)
        calls.append(chat.last_call_id)
        try:
            obj = core.parse_object(result)
            words = obj.get('words')
            if (set(obj) != {'words'} or not isinstance(words, list) or len(words) != 3
                    or any(not isinstance(w, str) or not w or any(c.isspace() for c in w) for w in words)):
                raise ValueError('Expected exactly three separate nonempty words')
            normalized = json.dumps({'visual_query': ' '.join(words)})
            core.parse_query(normalized)
            recovery.append({'call_id': chat.last_call_id, 'visual_query': ' '.join(words)})
            return normalized
        except (ValueError, TypeError) as exc:
            if attempt == 2:
                raise
            fix += '\nPrevious output: ' + result + '\nValidation error: ' + str(exc)


def load_run(args):
    manifest(args.output, args.hippomm_backbone)
    memory, events, vectors, dialogues, images = load_memory(args.memory_dir, args.hippomm_backbone)
    p = json.loads((args.output / 'protocol.json').read_text())['contract']
    if (p['backbone'] != args.hippomm_backbone or p['memory_dir'] != str(args.memory_dir.resolve())
            or p['max_output_tokens'] != args.hippomm_max_new_tokens):
        raise ValueError('Prepared API configuration differs')
    questions = inputs.read_lines(args.output / 'questions.jsonl')
    if len(questions) != p['questions']:
        raise ValueError('Question count differs')
    inputs.unique(questions)
    return p, memory, events, vectors, dialogues, images, questions


def run(args):
    p, _, events, vectors, dialogues, images, questions = load_run(args)
    emap = inputs.unique(events, 'event_id')
    path = args.output / 'qa_responses.jsonl'
    done = inputs.unique(inputs.read_lines(path)) if path.exists() else {}
    qmap = inputs.unique(questions)
    if not set(done) <= set(qmap):
        raise ValueError('Foreign completed question')
    encoder, encoder_lock = base.ClipText(args.device), threading.Lock()
    def encode(query):
        with encoder_lock:
            return encoder(query)

    def answer(index, q):
        directory = args.output / 'llm_cache' / f'Q{index:04d}'
        chat = transport.APIChat(directory, args.hippomm_backbone, args.hippomm_api_env_file,
                                 args.hippomm_max_new_tokens)
        calls, recovery, image_order = [], [], []
        rewrite_count = 0
        started = time.perf_counter()
        def llm(role, prompt):
            nonlocal rewrite_count, image_order
            paths = q['query_image_paths'] if role in ('fast', 'answer') else []
            actual_role = role
            if role == 'answer':
                evidence = json.loads(prompt.rsplit('\n', 1)[-1])
                ids = [e['event_id'] for e in evidence['memories']]
                if ids:
                    prompt, paths, image_order = original.reader_payload(q,
                        {'route': 'detailed', 'selected_event_ids': ids}, emap, images, dialogues,
                        args.memory_dir)
                    actual_role = 'answer_with_representatives'
            raw = chat(actual_role, prompt, paths)
            calls.append(chat.last_call_id)
            if role == 'rewrite':
                rewrite_count += 1
                if rewrite_count == 3:
                    raw = repaired_rewrite(chat, raw, core.query_prompt(q), calls, recovery)
            return raw
        trace = core.answer_question(q, events, vectors, dialogues, llm, encode)
        trace.update(backbone=args.hippomm_backbone, model=transport.MODELS[args.hippomm_backbone],
                     llm_calls=[str((directory / (c + '.json')).relative_to(args.output)) for c in calls],
                     query_format_recovery=recovery, reader_image_order=image_order,
                     historical_image_reads=sum(r['kind'] == 'historical_representative' for r in image_order),
                     elapsed_seconds=time.perf_counter() - started)
        return trace
    todo = [(i, q) for i, q in enumerate(questions, 1) if q['id'] not in done]
    with ThreadPoolExecutor(max_workers=args.hippomm_api_workers) as pool:
        futures = {pool.submit(answer, i, q): q['id'] for i, q in todo}
        for future in as_completed(futures):
            qid = futures[future]
            try:
                row = future.result()
                base.append(path, row)
                print(json.dumps({'id': qid, 'route': row['route'], 'answer': row['answer']}), flush=True)
            except Exception as exc:
                base.append(args.output / 'question_errors.jsonl', {'id': qid,
                            'type': type(exc).__name__, 'error': str(exc)})
                print(json.dumps({'id': qid, 'error': str(exc)}), flush=True)
                if getattr(exc, 'kind', '') in ('auth', 'quota', 'model_mismatch', 'protocol'):
                    for f in futures:
                        f.cancel()
                    raise


def analyze(args):
    p, memory, events, _, dialogues, images, questions = load_run(args)
    responses = inputs.read_lines(args.output / 'qa_responses.jsonl')
    if set(inputs.unique(responses)) != set(inputs.unique(questions)):
        raise ValueError('Incomplete answers; no final metrics written')
    if str(args.benchmark_manifest.resolve()) != p['evaluation_source']:
        raise ValueError('Wrong evaluation source')
    gold = inputs.evaluation_gold(args)
    qmap = inputs.unique(questions)
    emap = inputs.unique(events, 'event_id')
    rows = []
    _, provider_captions = caption_source(args.hippomm_backbone)
    for e in events:
        source_caption = provider_captions[inputs.sha(args.memory_dir / images[e['event_id']]['file'])]
        if e['caption'] != source_caption['caption']:
            raise ValueError('Memory caption differs from its backbone source')
        cached = [json.loads(path.read_text()) for path in
                  (args.memory_dir / 'llm_cache' / e['event_id']).glob('call_*.json')]
        matches = [c for c in cached if c['request']['role'] == 'summary'
                   and c['request']['prompt'] == core.summary_prompt(e, dialogues)]
        if (len(matches) != 1 or matches[0]['response']['raw_response'].strip() != e['summary']
                or matches[0]['response']['returned_model'] != transport.MODELS[args.hippomm_backbone]
                or matches[0]['response']['finish_reason'] != 'stop'):
            raise ValueError('Memory summary differs from its provider response')
    for r in responses:
        q = qmap[r['id']]
        if r['backbone'] != args.hippomm_backbone or r['model'] != transport.MODELS[args.hippomm_backbone]:
            raise ValueError('Mixed answer backbone')
        if any(emap[e]['task'] != q['task'] for e in r['selected_event_ids']):
            raise ValueError('Cross-task selected evidence')
        final_calls = []
        for name in r['llm_calls']:
            call = json.loads((args.output / name).read_text())
            req, out = call['request'], call['response']
            if (req['backbone'] != args.hippomm_backbone or out['returned_model'] != r['model']
                    or out['finish_reason'] != 'stop' or out.get('refusal')):
                raise ValueError('Invalid provider call provenance')
            if req['role'] not in ('fast', 'answer', 'answer_with_representatives') and req['image_paths']:
                raise ValueError('Retrieval unexpectedly received original images')
            if req['role'] in ('fast', 'answer') and req['image_paths'] != q['query_image_paths']:
                raise ValueError('Question-image payload differs')
            if req['role'] in ('answer', 'answer_with_representatives', 'format_mcq'):
                final_calls.append(call)
        if not final_calls or final_calls[-1]['response']['raw_response'].strip() != r['answer']:
            raise ValueError('Final answer differs from raw provider output')
        if r['route'] == 'detailed' and r['selected_event_ids']:
            prompt, paths, order = original.reader_payload(q, r, emap, images, dialogues, args.memory_dir)
            if (final_calls[-1]['request']['prompt'] != prompt
                    or final_calls[-1]['request']['image_paths'] != paths or r['reader_image_order'] != order):
                raise ValueError('Detailed answer used different original images')
        elif r['reader_image_order'] or r['historical_image_reads']:
            raise ValueError('Unexpected historical images outside nonempty detailed answers')
        g = gold[r['id']]
        labels = set(g['gold_ids'])
        rows.append({'id': r['id'], 'task': r['task'], 'route': r['route'],
                     'accuracy': float(r['answer'] == g['gold_choice']),
                     'format_error': r['answer'] not in ('A', 'B', 'C', 'D'),
                     'context_gold_hits': len(labels & set(r['context_round_ids'])), 'gold_count': len(labels)})
    hits, total = sum(r['context_gold_hits'] for r in rows), sum(r['gold_count'] for r in rows)
    summary = {'method': METHOD, 'backbone': args.hippomm_backbone, 'model': memory['model'],
        'questions': len(rows), 'correct': sum(r['accuracy'] for r in rows),
        'accuracy': sum(r['accuracy'] for r in rows) / len(rows),
        'format_errors': sum(r['format_error'] for r in rows),
        'fast_answers': sum(r['route'] == 'fast' for r in rows),
        'detailed_answers': sum(r['route'] == 'detailed' for r in rows),
        'context_source_micro_recall': hits / total if total else None,
        'recall_note': 'Micro source-round coverage; all-summary fast context is not Recall@5.',
        'representative_images': memory['events'], 'original_image_bytes': memory['original_image_bytes'],
        'memory_artifact_bytes': memory['memory_artifact_bytes'],
        'total_memory_bytes': memory['original_image_bytes'] + memory['memory_artifact_bytes'],
        'caption_source': memory['caption_source'], 'all_llm_roles_same_backbone': True}
    base.write_lines(args.output / 'per_question.jsonl', rows)
    base.dump(args.output / 'summary.json', summary)
    base.dump(args.output / 'completion_manifest.json', {'status': 'complete', 'questions': len(rows),
              'provider_and_image_payload_audit': 'passed',
              'artifacts': ['questions.jsonl', 'qa_responses.jsonl', 'per_question.jsonl', 'summary.json']})
    print(json.dumps(summary, indent=2), flush=True)


def add_arguments(parser):
    parser.add_argument('--hippomm-backbone', choices=['gpt5', 'deepseek'], default='gpt5')
    parser.add_argument('--hippomm-api-workers', type=int, default=4)
    parser.add_argument('--hippomm-api-env-file', type=Path,
                        default=Path('/storage/hewenwen/NTU Decentralized Agent/.env'))


def pipeline(args, parser):
    if args.dataset != 'memeye' or args.hippomm_api_workers < 1 or args.hippomm_max_new_tokens < 1:
        parser.error('hippomm_api supports MemEye and requires positive workers/token limit')
    default = ROOT / 'results/debug_caption_master_answer'
    target = ROOT / 'results/visual_memory_pipeline/hippomm_api' / args.hippomm_backbone / 'memeye'
    if args.output == default / args.phase:
        args.output = target / args.phase
    if args.phase == 'offline':
        if args.task or args.limit or args.image_files or args.memory_source or args.from_start:
            parser.error('hippomm_api uses the full fixed visual representative set')
        return build(args)
    if args.memory_path is not None:
        args.memory_dir = args.memory_path
    elif args.memory_dir == default / 'offline/memory':
        args.memory_dir = target / 'offline'
    if (args.reader_backend != 'local' or args.online_weighting is not None or args.retrieval is not None
            or args.query_image_captions or args.encode_queries or args.top_k not in (None, 5)
            or args.hippomm_confidence_threshold != .75 or args.hippomm_fallback_threshold != .4
            or args.hippomm_fallback_score != .6 or args.output.resolve() == args.memory_dir.resolve()):
        parser.error('Use hippomm_api backbone flags with unchanged HippoMM retrieval settings')
    if args.stage in ('prepare', 'all'):
        prepare(args)
    if args.stage in ('run', 'all'):
        run(args)
    if args.stage in ('analyze', 'all'):
        analyze(args)
